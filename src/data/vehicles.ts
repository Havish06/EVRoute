export function getVehicleById(id: string): VehicleSpec {
  return VEHICLE_DATABASE.find(v => v.id === id) || VEHICLE_DATABASE[0];
}

export function getVehicleBrands(): string[] {
  return Array.from(new Set(VEHICLE_DATABASE.map(v => v.manufacturer)));
}

export function getVehiclesByBrand(brand: string): VehicleSpec[] {
  return VEHICLE_DATABASE.filter(v => v.manufacturer === brand);
}
